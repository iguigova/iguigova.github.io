#!/usr/bin/env python3
"""Render the hub from hub.json, the one source for what it lists.

    ./build.py                  write index.html
    ./build.py --check          exit 1 if index.html is not what hub.json renders
    ./build.py --readme PATH    also write the profile README (iguigova/iguigova)
    ./build.py --profile PATH   also rewrite the "My GitHub is" line of profile.txt
    ./build.py --self-test

The profile line is matched by its prefix, so the line can move within the file.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from dataclasses import dataclass
from html import escape
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROFILE_PREFIX = "My GitHub is "


@dataclass(frozen=True)
class Item:
    name: str
    url: str
    blurb: str
    profile: str


@dataclass(frozen=True)
class Section:
    title: str
    items: tuple[Item, ...]


@dataclass(frozen=True)
class Link:
    name: str
    url: str
    note: str = ""


@dataclass(frozen=True)
class Hub:
    name: str
    tagline: str
    about: str
    github: str
    github_note: str
    hub: str
    sections: tuple[Section, ...]
    links: tuple[Link, ...]


def load(path: Path) -> Hub:
    d = json.loads(path.read_text())
    return Hub(
        name=d["name"], tagline=d["tagline"], about=d["about"], github=d["github"],
        github_note=d["github_note"], hub=d["hub"],
        sections=tuple(Section(s["title"], tuple(Item(**i) for i in s["items"])) for s in d["sections"]),
        links=tuple(Link(**link) for link in d["links"]),
    )


def href(url: str, hub: str) -> str:
    """A page under the hub is linked by its path, so it resolves on any origin serving it."""
    return url[len(hub):] if url.startswith(hub + "/") else url


def render_html(h: Hub) -> str:
    sections = "".join(
        f"""
    <section>
      <h2>{escape(s.title)}</h2>
      <div>"""
        + "".join(
            f"""
        <h3><a href="{escape(href(i.url, h.hub))}">{escape(i.name)}</a></h3>
        <p>{escape(i.blurb)}</p>"""
            for i in s.items
        )
        + """
      </div>
    </section>
"""
        for s in h.sections
    )
    links = "".join(
        f"""
          <li><a href="{escape(link.url)}">{escape(link.name)}</a>{": " + escape(link.note) if link.note else ""}</li>"""
        for link in h.links
    )
    return f"""<!doctype html>
<!-- Generated by build.py from hub.json; edit those, not this file. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(h.name)}</title>
<meta name="description" content="{escape(h.about)}">
<link rel="stylesheet" href="/brand.css">
</head>
<body>
<div class="wrap">
  <header>
    <div>
      <h1>{escape(h.name)}</h1>
      <p class="tag">{escape(h.tagline)}</p>
    </div>
  </header>

  <main>
    <section>
      <h2>About</h2>
      <div>
        <p>{escape(h.about)}</p>
      </div>
    </section>
{sections}
    <section>
      <h2>Elsewhere</h2>
      <div>
        <ul>{links}
        </ul>
      </div>
    </section>
  </main>

  <footer>
    <div class="line"><a href="{escape(h.github)}">{escape(h.github.removeprefix("https://"))}</a></div>
    <div class="band" aria-hidden="true"></div>
  </footer>
</div>
</body>
</html>
"""


def render_readme(h: Hub) -> str:
    first = h.name.split()[0]
    lists = "".join(
        f"\n**{s.title}**\n\n" + "".join(f"- [{i.name}]({i.url}): {i.profile}.\n" for i in s.items)
        for s in h.sections
    )
    return (
        f"<!-- Generated by build.py in iguigova.github.io from hub.json. -->\n"
        f"### Hi, I'm {first}\n\n{h.about} {h.tagline}\n{lists}\n"
        f"More on each at [{h.hub.removeprefix('https://')}]({h.hub}).\n"
    )


def render_profile_line(h: Hub) -> str:
    repos = ", ".join(f"{i.name} ({i.profile})" for s in h.sections for i in s.items)
    return f"{PROFILE_PREFIX}{h.github} — {h.github_note}. Its hub is {h.hub}. Notable repositories: {repos}."


def rewrite_profile(text: str, line: str) -> str:
    lines = text.splitlines(keepends=True)
    hits = [n for n, l in enumerate(lines) if l.startswith(PROFILE_PREFIX)]
    if len(hits) != 1:
        raise SystemExit(f"build.py: expected one line starting {PROFILE_PREFIX!r}, found {len(hits)}")
    lines[hits[0]] = line + "\n"
    return "".join(lines)


def self_test() -> int:
    h = load(HERE / "hub.json")
    failures: list[str] = []

    def want(cond: bool, what: str) -> None:
        print(f"  {'ok  ' if cond else 'FAIL'} {what}")
        if not cond:
            failures.append(what)

    html = render_html(h)
    names = [i.name for s in h.sections for i in s.items]
    want(all(f">{n}</a></h3>" in html for n in names), "every item is on the page")
    want('href="/stitchback/"' in html, "a page under the hub is linked by its path")
    want(f"<p>{escape(h.about)}</p>" in html, "the about line is the data's")
    readme = render_readme(h)
    want(all(f"[{n}](" in readme for n in names), "every item is in the README")
    line = render_profile_line(h)
    want(line.startswith(PROFILE_PREFIX) and h.github_note in line and all(n in line for n in names),
         "the profile line names the note and every item")
    with tempfile.TemporaryDirectory() as t:
        p = Path(t) / "profile.txt"
        p.write_text("a\nMy GitHub is old\nb\n")
        out = rewrite_profile(p.read_text(), line)
        want(out == f"a\n{line}\nb\n", "only the GitHub line is rewritten, in place")
    try:
        rewrite_profile("a\nb\n", line)
        want(False, "a profile without the line is refused")
    except SystemExit:
        want(True, "a profile without the line is refused")
    print(f"build.py self-test: {'FAIL' if failures else 'PASS'}")
    return 1 if failures else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--readme", type=Path)
    ap.add_argument("--profile", type=Path)
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    h = load(HERE / "hub.json")
    index = HERE / "index.html"
    html = render_html(h)
    if a.check:
        if index.read_text() != html:
            print("build.py: index.html is not what hub.json renders; run ./build.py", file=sys.stderr)
            return 1
        return 0
    index.write_text(html)
    if a.readme:
        a.readme.write_text(render_readme(h))
    if a.profile:
        a.profile.write_text(rewrite_profile(a.profile.read_text(), render_profile_line(h)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
